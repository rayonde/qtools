    def extract_beam_info(result, n_beams):
        """Extract beam parameters from fit result into structured list."""
        beams_info = []
        for i in range(n_beams):
            if n_beams == 1:
                prefix_amp = 'amplitude'
                prefix_xo = 'xo'
                prefix_yo = 'yo'
                prefix_sx = 'sigma_x'
                prefix_sy = 'sigma_y'
                prefix_theta = 'theta'
            else:
                prefix = f'beam{i}_'
                prefix_amp = f'{prefix}amplitude'
                prefix_xo = f'{prefix}xo'
                prefix_yo = f'{prefix}yo'
                prefix_sx = f'{prefix}sigma_x'
                prefix_sy = f'{prefix}sigma_y'
                prefix_theta = f'{prefix}theta'

            beam = {
                'id': i + 1,
                'amplitude': result.values[prefix_amp],
                'xo': result.values[prefix_xo] * pixel_size,
                'yo': result.values[prefix_yo] * pixel_size,
                'sigma_x': result.values[prefix_sx] * pixel_size * scale,
                'sigma_y': result.values[prefix_sy] * pixel_size * scale,
                'theta': (result.values[prefix_theta] / np.pi * 180) % 180,
                'xo_pix': result.values[prefix_xo],
                'yo_pix': result.values[prefix_yo],
            }
            beams_info.append(beam)
        return beams_info

    def plot_beams(b_waist, beams_info, result, n_beams):
        """Plot beam profile with ellipses, arrows, 1D slices, and parameter annotation."""
        scale = 1e3
        ps = pixel_size * scale

        fig, ax = plt.subplots(constrained_layout=True)
        # 1D slice along x (top inset, sharex=ax)
        ax_histx = ax.inset_axes([0, 1.05, 1, 0.25], sharex=ax)
        # 1D slice along y (right inset, sharey=ax)
