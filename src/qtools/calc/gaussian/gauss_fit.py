class Profile():
    def __init__(self):
        self.data = np.array([])
        self.height = 0
        self.width = 0
        self.bit_depth = np.uint8
        self.mm = {}
        # self.cmd = [0, 0]
        self.fit_data = np.array([])
        self.popt = []
        self.pcov = []
        self.sigma_0 = 0
        self.sigma_1 = 0
        # self.angle = 0

    def raw2array(self, raw_filename, bit_depth=8):
        """
        file to read the binary RAW file generated by flycap
        or coriander into a numpy 2D array
        :param raw_filename: name of the raw file
        :param bit_depth: specify if 8 or 16 bits
        :return: it returns a numpy 2D array
        """
        if bit_depth == 16:
            self.bit_depth = np.uint16
        else:
            self.bit_depth = np.uint8
        data = np.fromfile(raw_filename, dtype=self.bit_depth)

        # print(int(np.sqrt(len(data) / 12) * 4))
        self.width = int(np.sqrt(len(data) / 12) * 4)
        self.height = int(np.sqrt(len(data) / 12) * 3)
        # self.height=1024
        # self.width=1280
        self.data = data.reshape(self.height, self.width)
        self.mm = self.moment()

    def frame2array(self, frame):
        """
        Initializes the beam profile from a frame
        captured using opencv (the cv2 backend)
        :param frame: frame captured with cv2 or any other 2D numpy array
        """
        self.height, self.width = frame.shape
        self.data = frame
        self.bit_depth = frame.dtype

    def moment(self):
        _, binary = cv2.threshold(self.data.astype(dtype='uint8'),
                                  0,
                                  1,
                                  cv2.THRESH_BINARY + cv2.THRESH_OTSU)
        data_f = self.data * (binary > 0)
        return cv2.moments(data_f)

    @property
    def x_bar(self):

        return self.mm['m10']/self.mm['m00']

    @property
    def y_bar(self):
        return self.mm['m01']/self.mm['m00']

    @property
    def angle(self):
        u11 = (self.mm['m11'] - self.x_bar * self.mm['m01']) / self.mm['m00']
        u20 = (self.mm['m20'] - self.x_bar * self.mm['m10']) / self.mm['m00']
        u02 = (self.mm['m02'] - self.y_bar * self.mm['m01']) / self.mm['m00']
        if u20 == u02:
            return 0
        else:
            return 0.5 * np.arctan(2 * u11 / (u20 - u02))

    @property
    def eig(self):
        u11 = (self.mm['m11'] - self.x_bar * self.mm['m01']) / self.mm['m00']
        u20 = (self.mm['m20'] - self.x_bar * self.mm['m10']) / self.mm['m00']
        u02 = (self.mm['m02'] - self.y_bar * self.mm['m01']) / self.mm['m00']
        return 2*2**.5*(u20+u02+((u20-u02)**2+4*u11**2)**.5)**.5, 2*2**.5*(u20+u02-((u20-u02)**2+4*u11**2)**.5)**.5

    @property
    def rowmaxs(self):
        rows = np.arange(np.shape(self.data)[0])
        return rows, [np.max(self.data[i,:]) for i in rows]

    @property
    def colmaxs(self):
        cols = np.arange(np.shape(self.data)[1])
        return cols, [np.max(self.data[:,i]) for i in cols]

        #get the max number index 
   
    def maxrow_col(self):
        rows_cols = divmod(np.argmax(self.data[10:]),np.shape(self.data)[1])
        rows = rows_cols[0]+10
        cols = rows_cols[1] 
        return rows , cols

    def fitted(self, fix_theta=False):
        """
        fitting of the gaussian distribution using the least square method.
        the relevant parameters are returned as properties of the object
        :param fix_theta: if True, fix theta=0 (no rotation, aligned with x/y axes)
        """
        x_g = np.linspace(0, self.width-1, self.width)
        y_g = np.linspace(0, self.height-1, self.height)
        grid = np.empty((self.width*self.height, 2))
        x, y = np.meshgrid(x_g, y_g)
        grid[:,0] = x.flatten()
        grid[:,1] = y.flatten()

        # Start finding the parameters for the fit.
        p = Parameters()
        p.add('amplitude', value=np.max(self.data.flatten()), min=0)
        p.add('yo', value=self.y_bar)
        p.add('xo', value=self.x_bar)
        p.add('sigma_y', value=100, min=0)
        p.add('sigma_x', value=100, min=0)
        p.add('offset', value=np.median(self.data), min=0)
        if fix_theta:
            p.add('theta', value=0, vary=False)
        else:
            p.add('theta', value=self.angle)
        return fit_mod.fit(self.data.flatten(), x=grid, params=p)
    

    def fitted_multi_beam(self, n_beams=1, threshold_factor=0.5, fix_theta=False):
        """
        Fit multiple gaussian beams by segmenting the image
        :param n_beams: number of beams to fit
        :param threshold_factor: threshold multiplier for beam separation
        :param fix_theta: if True, fix theta=0 (no rotation, aligned with x/y axes)
        :return: list of fit results
        """
        if n_beams == 1:
            return [self.fitted(fix_theta=fix_theta)]
        
        # Auto-detect background threshold using Otsu
        _, binary = cv2.threshold(self.data.astype('uint8'), 0, 1,
                                cv2.THRESH_BINARY + cv2.THRESH_OTSU)
        bg_threshold = np.max(self.data[binary == 0])  # Max value in background region
        
        # Create mask for valid region
        valid_mask = self.data > bg_threshold
        valid_indices = np.where(valid_mask.flatten())[0]

        # Find local maxima
        local_max = maximum_filter(self.data, size=local_size) == self.data
        coords = np.argwhere(local_max)
        
        # Get intensity at each peak
        intensities = self.data[coords[:, 0], coords[:, 1]]
        
        # Sort by intensity and take top n_beams
        top_indices = np.argsort(intensities)[-n_beams:]
        peak_coords = coords[top_indices]
        
        #################################################
        def multi_gauss_flat(x, **params):
            result = np.zeros_like(x[:, 0], dtype=float)
            for i in range(n_beams):
                prefix = f'beam{i}_'
                amp = params[f'{prefix}amplitude']
                xo = params[f'{prefix}xo']
                yo = params[f'{prefix}yo']
                sx = params[f'{prefix}sigma_x']
                sy = params[f'{prefix}sigma_y']
                theta = params[f'{prefix}theta']
                
                result += gauss_flat(x, amp, xo, yo, sx, sy, theta, 0)
            
            result += params['offset']
            return result
        
        #################################################
        # Setup grid for valid region only
        x_g = np.linspace(0, self.width-1, self.width)
        y_g = np.linspace(0, self.height-1, self.height)
        x, y = np.meshgrid(x_g, y_g)
        grid = np.column_stack([x.flatten()[valid_indices], 
                                y.flatten()[valid_indices]])
        
            # Setup parameters
        p = Parameters()
        for i in range(n_beams):
            y_peak, x_peak = peak_coords[i]
            prefix = f'beam{i}_'
            p.add(f'{prefix}amplitude', value=np.max(self.data), min=0)
            p.add(f'{prefix}xo', value=x_peak)
            p.add(f'{prefix}yo', value=y_peak)
            p.add(f'{prefix}sigma_x', value=50, min=0)
            p.add(f'{prefix}sigma_y', value=50, min=0)
            if fix_theta:
                p.add(f'{prefix}theta', value=0, vary=False)
            else:
                p.add(f'{prefix}theta', value=0)

        p.add('offset', value=np.median(self.data), min=0)

        model = Model(multi_gauss_flat)
        return model.fit(self.data.flatten()[valid_indices], x=grid, params=p)


