            # Extract 1D slices
            x_positions = np.arange(b_waist.width)
            y_positions = np.arange(b_waist.height)

            y_idx = int(round(yo_pix))
            y_idx = np.clip(y_idx, 0, b_waist.height - 1)
            data_x = b_waist.data[y_idx, :].astype(float)

            x_idx = int(round(xo_pix))
            x_idx = np.clip(x_idx, 0, b_waist.width - 1)
            data_y = b_waist.data[:, x_idx].astype(float)

            # 1D Gaussian fit
            fit_x = amplitude * np.exp(-((x_positions - xo_pix)**2) / (2 * sx_pix**2)) + offset
            fit_y = amplitude * np.exp(-((y_positions - yo_pix)**2) / (2 * sy_pix**2)) + offset

            # Use actual pixel positions
            x_pos_um = x_positions * ps
            y_pos_um = y_positions * ps

            # Plot 1D slices in inset axes: data (blue/green), fit (black dashed)
